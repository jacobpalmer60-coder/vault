'use strict';
const assert=require('node:assert/strict');
const {hash,cohort,makeSeries,example,fit,evaluate,datePlus}=require('./market-history/relative-growth');
const a=Array.from({length:100},(_,i)=>'league'+i),train=a.find(k=>hash(k)%5!==0),test=a.find(k=>hash(k)%5===0);
assert.equal(cohort('2024-07-31',train),'train');assert.equal(cohort('2024-08-02',train),null);
assert.equal(cohort('2024-07-31',test),null);assert.equal(cohort('2025-08-01',train),null);assert.equal(cohort('2025-08-01',test),'test');
assert.equal(cohort('2025-07-31',test),null);assert.equal(datePlus('2024-08-01',365),'2025-08-01');
const book=makeSeries({dates:['2024-01-01','2024-01-02','2024-01-03','2024-01-12'],players:{a:[0,100,null,-100,200]}});
assert.equal(book.at('a','2023-12-31'),null);assert.equal(book.at('a','2024-01-02'),100);
assert.equal(book.at('a','2024-01-03'),0);assert.equal(book.at('a','2024-01-11'),null);assert.equal(book.at('a','2024-01-12'),200);
const p={now:100,before:80,after:120},q={now:200,before:200,after:220};
const x=example([p],[q]),y=example([q],[p]);
assert.ok(x.target>0&&x.future<0,'relative appreciation can differ from absolute future value');
for(const k of ['target','feature','initial','future'])assert.ok(Math.abs(x[k]+y[k])<1e-12);
assert.equal(example([{...p,after:null}],[q]),null);assert.ok(example([{...p,after:0}],[q]));
const rows=Array(100).fill(x),m=fit(rows);assert.ok(m.beta>0);assert.equal(fit(Array(100).fill(y)).beta,m.beta);
const r=evaluate([x,y],m.beta);assert.equal(r.n,2);assert.ok(r.trendGrowthMAE<r.baselineGrowthMAE);assert.equal(r.pairedGrowthBetter,2);
assert.equal(evaluate([],0).baselineGrowthMAE,null);
console.log('PASS chronological and league-key holdout, strict as-of prices, relative growth, orientation symmetry and matched baseline');

const premium=require('./market-history/premium-validation');
const hist={dates:['2025-01-01','2025-01-16'],tables:[{'n:a':50},{'n:a':99}]};
assert.equal(premium.snapshot(hist,'2025-01-16'),null);
assert.equal(premium.snapshot(hist,'2025-01-17')['n:a'],50);
assert.equal(premium.snapshot(hist,'2025-02-01')['n:a'],99);
const aa=[{name:'a',now:100}],bb=[{name:'b',now:150}];
const pr=premium.priceRow(aa,bb,hist.tables[0]),rev=premium.priceRow(bb,aa,hist.tables[0]);
assert.equal(pr.gaps.at(-1),0);assert.ok(pr.gaps.every((v,i)=>Math.abs(v+rev.gaps[i])<1e-9));
assert.equal(premium.priceRow(aa,bb,{'n:a':-100}),null);
const ps=premium.summarize([pr,rev]);assert.equal(ps.weights['1'].fairUnder14,2);assert.equal(ps.weights['0'].fairUnder14,0);assert.equal(ps.weights['1'].closerToEven,2);
console.log('PASS lagged premium snapshot, zero/partial/full adjustment and paired completed-trade price agreement');

const snaps=[{date:'2025-08-01',picks:{'2027-1-mid':{sf:4000},'2027-2-mid':{sf:2000}}},{date:'2025-08-05',picks:{'2027-1-mid':{sf:9000}}}];
const pick=premium.pickAt(snaps,'p2027-1','2025-08-02','sf');assert.equal(pick.now,4000);assert.equal(pick.premiumKey,'k:2027-1');
assert.equal(premium.pickAt(snaps,'p2028-1','2025-08-02','sf'),null);assert.equal(premium.pickAt(snaps,'p2027-1','2025-08-02','sf_tep'),null);assert.equal(premium.pickAt(snaps,'p2027-1','2025-08-14','sf'),null);
assert.equal(premium.pickAt(snaps,'p2027-5','2025-08-02','sf'),null);assert.equal(premium.pickAt(snaps,'p2027-1','2025-07-31','sf'),null);
const mixed=premium.priceRow([pick],[{name:'b',now:2000,type:'player'}],{'k:2027-1':-50});assert.equal(mixed.gaps.at(-1),0);
assert.deepEqual(premium.pickGroups([pick],[{name:'b',now:2000,type:'player'}]),['mixed-player-pick','first-round-included','two-plus-draft-years-out']);
assert.equal(premium.priceRow([pick,pick],[{name:'b',now:4000}],{'k:2027-1':-50}).gaps.at(-1),0);
console.log('PASS exact-year round pick prices, no future/fallback prices, duplicate pick quantities and mixed cohort premiums');

const cal=require('./market-history/premium-calibration');
const c1=cal.row([{name:'a',now:100,type:'player'}],[{name:'pick',premiumKey:'k:2027-1',type:'pick',now:150}],{'n:a':50,'k:2027-1':50},'l1','2024-07-01');
const c2=cal.row([{name:'pick',premiumKey:'k:2027-1',type:'pick',now:150}],[{name:'a',now:100,type:'player'}],{'n:a':50,'k:2027-1':50},'l1','2024-07-01');
assert.equal(c1.kind,'mixed');assert.deepEqual(c1.gaps,c2.gaps);assert.equal(c1.gaps[cal.GRID.findIndex(w=>w.player===1&&w.pick===0)],0);
const training=Array.from({length:200},(_,i)=>({...c1,league:'train'+i}));
const candidate=cal.select(training);assert.equal(cal.GRID[candidate.index].player,1);assert.equal(cal.GRID[candidate.index].pick,0);
const validation=Array.from({length:40},(_,i)=>({...c1,league:'test'+i,month:'2025-08'}));
const calibrated=cal.report(training,validation);assert.equal(calibrated.test.versusRaw.closer,40);assert.equal(calibrated.test.versusRaw.approximate95CI.length,2);
assert.equal(cal.report(training.slice(0,20),validation).candidate,null);assert.equal(cal.report(training,[]).test.versusRaw,null);
assert.deepEqual(cal.report(training,validation.map(r=>({...r,gaps:r.gaps.map(v=>200-v)}))).candidate,calibrated.candidate);
console.log('PASS separate player/pick weight selection, training-only model choice, sample gates, mirrored prices and paired league-cluster intervals');
