#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const read=n=>fs.readFileSync(path.join(__dirname,'..',n),'utf8');
const D=require('../draft-rules.js'),A=require('../activity-model.js');
const teams=Array.from({length:8},(_,i)=>({rosterId:i+1,teamName:'Team '+(i+1),record:{wins:i+2,losses:12-i},picks:[{season:2027,round:1,original:i+1,value:5000},{season:2027,round:2,original:i+1,value:2000}]}));
const rosters=teams.map((t,i)=>({roster_id:t.rosterId,settings:{ppts:1000+i*10,ppts_decimal:25}}));
const bracket=[{r:1,t1:3,t2:4,w:3,l:4,p:5},{r:2,t1:5,t2:6,w:5,l:6,p:3},{r:3,t1:7,t2:8,w:8,l:7,p:1}],league={settings:{playoff_teams:6}};
const out=D.build({teams,rosters,bracket,league});
assert.equal(out.complete,true);
assert.equal(out.qualifierSource,'sleeper-bracket');
assert.deepEqual(out.rows.map(r=>[r.rosterId,r.slot]),[['1',1],['2',2],['4',3],['3',4],['6',5],['5',6],['7',7],['8',8]]);
assert.equal(D.mpfOf(rosters[0]),1000.25);
assert.equal(D.mpfOf({settings:{}}),null);
assert.deepEqual(['linear','snake','3rr'].map(x=>D.orderInRound(1,2,8,x)),[1,8,8]);
assert.equal(D.orderInRound(1,3,8,'3rr'),8);
assert.equal(D.orderInRound(1,4,8,'3rr'),1);
const moved=structuredClone(teams);
moved[0].picks.pop();moved[1].picks.push({season:2027,round:2,original:1,value:2000});
const picks=D.applyPicks(moved,2027,out,'linear');
assert.equal(picks.length,16);
assert.equal(picks.filter(p=>p.original==='1').length,2);
assert.ok(picks.some(p=>p.original==='1'&&p.holder==='2'&&p.roundSlot===1));
assert.deepEqual(D.build({teams:[...teams].reverse(),rosters,bracket,league}).rows.map(r=>[r.rosterId,r.slot]),out.rows.map(r=>[r.rosterId,r.slot]));
const partial=D.build({teams,rosters,bracket:[{r:1,t1:3,t2:4}],league});
assert.equal(partial.complete,false);
const early=D.build({teams,rosters,bracket:[{r:1,t1:3,t2:4,w:3,l:4},{r:1,t1:5,t2:6,w:5,l:6}],league});
assert.deepEqual(early.rows.find(r=>r.rosterId==='4').range,[3,4],'first-round eliminated teams get a band, never a fabricated slot');
assert.equal(early.rows.find(r=>r.rosterId==='4').slot,null);
const missing=D.build({teams,rosters:rosters.slice(1),bracket,league});
assert.equal(missing.rows.find(r=>r.rosterId==='1').slot,null);
const overrides=D.build({teams,rosters,bracket,league,settings:{manualSlots:{'1':2}}});
assert.equal(overrides.rows.find(r=>r.rosterId==='1').slot,2);
assert.equal(overrides.rows.find(r=>r.rosterId==='2').slot,null);
assert.ok(D.build({teams,rosters,bracket,league,settings:{manualSlots:{'1':2,'2':2}}}).warnings.some(w=>w.includes('collision')));
console.log('PASS all-manager MPF, playoff placement, future draft unknowns, 3RR/snake, original-versus-holder and override collision checks');
const users=teams.map(t=>({user_id:'u'+t.rosterId,display_name:t.teamName}));
const names={p1:{first_name:'One'},p2:{first_name:'Two'},p3:{first_name:'Three'}};
const r=teams.map(t=>({roster_id:t.rosterId,owner_id:'u'+t.rosterId}));
const trade={transaction_id:'T',type:'trade',status:'complete',created:1700000000000,roster_ids:[2,7],adds:{p1:2,p2:7},draft_picks:[{season:2027,round:1,roster_id:7,previous_owner_id:7,owner_id:2}]};
const move={transaction_id:'M',type:'free_agent',status:'complete',created:1700000100000,roster_ids:[4],adds:{p3:4}};
const pending={transaction_id:'P',type:'trade',status:'pending',created:1700000200000,roster_ids:[5,6]};
const data=A.build({weeks:[[trade,trade,move],null,[pending]],rosters:r,users,players:names,season:2026,leagueId:'L',drafts:[{draft:{draft_id:'D',start_time:1700000000000},picks:[{pick_no:1,round:1,draft_slot:1,roster_id:8,player_id:'p3'}]}]});
assert.equal(data.transactions,3);
assert.equal(data.draftPicks,1);
assert.deepEqual(data.missingWeeks,[1]);
assert.equal(A.filter(data.events,{kind:'trade'}).length,1);
assert.equal(A.filter(data.events,{kind:'trade',status:'all'}).length,2);
assert.equal(A.filter(data.events,{kind:'draft'}).length,1);
assert.equal(A.filter(data.events,{kind:'roster'}).length,1);
for(const who of ['2','7','4','8'])assert.equal(A.filter(data.events,{team:who}).length,1);
assert.equal(A.filter(data.events,{team:'1'}).length,0);
assert.equal(A.filter(data.events,{team:'6',status:'all'}).length,1);
assert.equal(A.filter(data.events,{kind:'trade'})[0].participants.length,2);
assert.ok(A.filter(data.events,{kind:'trade'})[0].affected.find(x=>x.id==='2').gets.some(x=>x.includes('2027')));
assert.ok(A.filter(data.events,{kind:'trade'})[0].affected.find(x=>x.id==='7').loses.some(x=>x.includes('2027')));
const reversed=A.build({weeks:[[move,trade],null,[pending]],rosters:r,users,players:names});
assert.equal(reversed.transactions,3);
const unknown=A.build({weeks:[[{...trade,draft_picks:[{season:2027,round:1,roster_id:7,owner_id:2}]}]],rosters:r,users,players:names});
assert.ok(!unknown.events[0].participants.includes('undefined'));
console.log('PASS all-manager trades, nontrades, draft selections, partial-week coverage, dedup and owner-attribution safety');
assert.match(read('vault-nav.js'),/activity\.html/);
assert.match(read('draft-center.js'),/VaultDraftOrder\.build/);
assert.match(read('activity.js'),/VaultActivity\.build/);
assert.match(read('vault.css'),/vault-event-card/);
console.log('PASS integrated pages and shared styling');
