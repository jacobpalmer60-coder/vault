#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const get=p=>fs.readFileSync(path.join(__dirname,'..',p),'utf8');
const proof=get('proof.html'), market=get('market.html'), overview=get('app.html');
assert.match(proof,/id="vault-nav"/);
assert.match(proof,/Archived proof of the previous verdict/);
assert.match(proof,/untouched chronological holdout/);
assert.match(proof,/82\.83% vs 62\.06%/);
assert.match(proof,/86\.36% vs 63\.46%/);
assert.match(proof,/og:url" content="[^"]*proof\.html"/);
assert.match(market,/data-tab="movers"/);
assert.match(market,/data-tab="highs"/);
assert.match(market,/\['highs', 'Highs & lows'\]/);
assert.doesNotMatch(market,/key === 'moves' \|\| key === 'highs'/);
assert.match(market,/pointerup/);
assert.match(overview,/pointerup/);
assert.match(overview,/tabindex="0" role="img"/);
assert.match(overview,/ArrowLeft.*ArrowRight/);
for(const page of ['proof.html','market.html','app.html']){
  const s=get(page);
  for(const match of s.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new Function(match[1]);
}
const draft=get('draft.html'), nav=get('vault-nav.js'), css=get('vault.css');
assert.match(nav,/draft\.html/);
assert.match(draft,/Max Points For/);
assert.match(draft,/Traded picks/);
assert.match(draft,/vault-mobile-table/);
assert.match(get('draft-center.js'),/data-label="Current holder"/);
assert.match(get('draft-center.js'),/data-label="Placement basis"/);
assert.match(css,/vault-mobile-table/);
assert.match(get('draft-rules.js'),/ppts_decimal/);
assert.match(draft,/not the complete draft order/i);
assert.match(css,/min-height: 42px/);
assert.match(get('activity.html'),/League Activity/);
assert.match(get('activity-model.js'),/draftPicks/);
assert.match(get('activity.js'),/VaultActivity\.build/);
const activityHtml=get('activity.html'),activityScript=get('activity.js');
assert.ok(activityHtml.indexOf('id="activitySeason"') < activityHtml.indexOf('id="activityBody"'), 'season selector remains visible after a data error');
assert.match(activityScript,/href\('team-analyzer\.html',\{team:a\.id\},e\.leagueId\)/);
assert.match(activityScript,/href\('trade_grades\.html',\{\},leagueId\)/);
assert.match(nav,/activity\.html/);
for(const match of draft.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)) new Function(match[1]);
const core=get('vault-core.js');
assert.match(core,/async fetchLeagueTradeWeeks\(/);
assert.match(core,/Math\.min\(8, total\)/);
assert.match(core,/attempt < 2/);
assert.match(core,/fetchLeagueTradeWeeks\(seasonChain, leagueId, onProgress\)/);
assert.match(core,/const missingWeeks = weeks\.flatMap/);
assert.match(get('managers.html'),/Loading trade history…/);
assert.match(get('trade_grades.html'),/Loading trade history…/);
const managers=get('managers.html'),grades=get('trade_grades.html'),evidence=get('trade-evidence.js');
assert.match(managers,/id="tradeEvidence"/);
assert.match(grades,/id="tradeEvidence"/);
assert.match(managers,/id="manager-toggle-\$\{s\.rosterId\}"/);
assert.match(managers,/aria-sort=/);
assert.match(managers,/s\.pricedTrades \? signedCell\(s\.netValue\)/);
assert.doesNotMatch(managers,/<tr class="align-top cursor-pointer/);
assert.match(grades,/evidence\.reliableGrades/);
assert.match(grades,/visibleLimit = gradePageSize\(\)/);
assert.match(get('draft-center.js'),/pickPageSize/);
assert.match(draft,/id="morePicks"/);
assert.match(grades,/id="moreGrades"/);
assert.match(evidence,/function byManager\(/);
console.log('PASS proof, Market tabs, accessible charts, Draft Center, League Activity, manager parity, graded evidence and progressive trade lists');
